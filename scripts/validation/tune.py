"""Identical-budget random-search hyperparameter tuning per model family (validation set only).

Why: the paper uses fixed, untuned hyperparameters, so the ranking of conditions could be a tuning
artefact. This tunes every family with the same number of trials, scoring on the shared
VALIDATION split of the paper's split (split.seed=42); the test split is never touched.

Training data: the IID partitions' bank_A and bank_B (seed 42), i.e. what a single bank would hold.
The score of a configuration is the mean validation AP over these two banks. Class re-weighting is
deliberately not searched: the KD protocol averages probabilities, so they must stay on the natural
likelihood scale (see configs/models.yaml).

Output: ``configs/val_tuned.yaml`` (profile overriding ``models`` and keeping the epoch budget
invariant: fedavg.local_epochs = kd.mlp_epochs_per_round = epochs / num_rounds) and
``<out>/tuning_trials.csv`` with every trial.
"""
from __future__ import annotations

import argparse
import time
from pathlib import Path

import heterofl  # noqa: F401  (OpenMP load order)
import numpy as np
import pandas as pd
import yaml
from sklearn.metrics import average_precision_score

from heterofl.data.pipeline import prepare_bundle, prepare_scenario
from heterofl.models.model_factory import create_model
from heterofl.utils.config import load_config

SPACES = {
    "xgboost": {"n_estimators": [100, 300, 600], "max_depth": [3, 4, 6, 8],
                "learning_rate": [0.03, 0.05, 0.1, 0.2], "subsample": [0.6, 0.8, 1.0],
                "colsample_bytree": [0.5, 0.8, 1.0], "min_child_weight": [1.0, 3.0, 5.0, 10.0],
                "reg_lambda": [1.0, 5.0, 10.0]},
    "random_forest": {"n_estimators": [200, 400], "max_depth": [None, 12, 20, 30],
                      "min_samples_leaf": [1, 2, 5], "max_features": ["sqrt", "log2", 0.3]},
    "mlp": {"hidden_sizes": [[64, 32], [128, 64], [128, 64, 32], [256, 128]],
            "dropout": [0.0, 0.1, 0.3], "learning_rate": [3e-4, 1e-3, 3e-3],
            "weight_decay": [0.0, 1e-5, 1e-4], "epochs": [10, 20, 30],
            "batch_size": [256, 512, 1024]},
}


def sample(rng: np.random.Generator, space: dict) -> dict:
    return {k: v[int(rng.integers(len(v)))] for k, v in space.items()}


def main(config: Path, out: Path, trials: int, seed: int, n_jobs: int) -> None:
    cfg = load_config(config)
    bundle = prepare_bundle(cfg)
    sc = prepare_scenario(cfg, bundle, 42, "iid")
    Xv, yv = sc.validation()
    banks = {b: sc.bank(b) for b in ("A", "B")}
    rng = np.random.default_rng(seed)
    base = cfg["models"]
    rows, best = [], {}
    for fam, space in SPACES.items():
        configs = [dict(base[fam])] + [{**base[fam], **sample(rng, space)} for _ in range(trials - 1)]
        for i, params in enumerate(configs):
            aps, t0 = [], time.perf_counter()
            for b, (X, y) in banks.items():
                m = create_model(fam, {fam: params}, seed=1000 + i, n_jobs=n_jobs)
                m.fit(X, y)
                aps.append(average_precision_score(yv, m.predict_proba(Xv)))
            rows.append({"family": fam, "trial": i, "is_default": i == 0, "val_ap_mean": float(np.mean(aps)),
                         "val_ap_A": aps[0], "val_ap_B": aps[1], "seconds": time.perf_counter() - t0,
                         "params": repr(params)})
            print(f"{fam} trial {i:2d} val AP {np.mean(aps):.4f} ({rows[-1]['seconds']:.0f}s)", flush=True)
        fam_rows = [r for r in rows if r["family"] == fam]
        j = int(np.argmax([r["val_ap_mean"] for r in fam_rows]))
        best[fam] = configs[j]
        print(f"==> {fam}: best trial {j} val AP {fam_rows[j]['val_ap_mean']:.4f} "
              f"(default {fam_rows[0]['val_ap_mean']:.4f})", flush=True)
    out.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(out / "tuning_trials.csv", index=False)
    rounds = int(cfg["federation"]["num_rounds"])
    ep = int(best["mlp"]["epochs"])
    if ep % rounds:
        raise SystemExit(f"tuned MLP epochs {ep} not divisible by num_rounds {rounds}")
    doc = {"base_config": "val_base.yaml", "profile": "validation_tuned", "results_dir": "results/val_tuned",
           "models": {f: {k: v for k, v in p.items()} for f, p in best.items()},
           "fedavg": {"local_epochs": ep // rounds}, "kd": {"mlp_epochs_per_round": ep // rounds}}
    header = ("# AUTO-GENERATED by scripts/validation/tune.py (random search, validation AP only, split.seed=42).\n"
              "# Evaluate ONLY with split.seed=42 (tuning used that split's validation set; other split seeds\n"
              "# have test rows that were in its training pool/validation set).\n")
    (config.parent / "val_tuned.yaml").write_text(header + yaml.safe_dump(doc, sort_keys=False))
    print("wrote", config.parent / "val_tuned.yaml")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", type=Path, default=Path("configs/val_base.yaml"))
    ap.add_argument("--out", type=Path, default=Path("paper_results/validation/tuning"))
    ap.add_argument("--trials", type=int, default=20)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--n-jobs", type=int, default=4)
    a = ap.parse_args()
    main(a.config, a.out, a.trials, a.seed, a.n_jobs)
